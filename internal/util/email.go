// ValidateAndSanitizeEmail kiểm tra và làm sạch địa chỉ email, đảm bảo 100% là ký tự ASCII chuẩn.
// Tự động chuyển đổi dấu tiếng Việt về chữ không dấu tương ứng và loại bỏ các ký tự điều khiển/lạ.
func ValidateAndSanitizeEmail(rawEmail string) (string, error) {
	trimmed := strings.TrimSpace(rawEmail)
	if trimmed == "" {
		return "", fmt.Errorf("địa chỉ email không được để trống")
	}

	var sb strings.Builder
	for _, r := range trimmed {
		// 1. Chuyển đổi ký tự tiếng Việt có dấu về không dấu
		if repl, ok := vietnameseMap[r]; ok {
			sb.WriteRune(repl)
			continue
		}

		// 2. Giữ lại các ký tự ASCII in được
		if r <= unicode.MaxASCII && !unicode.IsControl(r) && !unicode.IsSpace(r) {
			sb.WriteRune(r)
		}
	}

	sanitized := strings.ToLower(sb.String())

	// 3. Validate format email chuẩn
	re := regexp.MustCompile(`^[a-zA-Z0-9.!#$%&'*+/=?^_` + "`" + `{|}~-]+@[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?(?:\.[a-zA-Z0-9](?:[a-zA-Z0-9-]{0,61}[a-zA-Z0-9])?)+$`)
	if !re.MatchString(sanitized) {
		_, err := mail.ParseAddress(sanitized)
		if err != nil {
			return "", fmt.Errorf("định dạng email '%s' không hợp lệ", rawEmail)
		}
	}

	return sanitized, nil
}
